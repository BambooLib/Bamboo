package io.github.deopping.bamboo.world.api

/**
 * Represents the weather conditions of a world.
 *
 * @author DeOpping
 * @since 1.0.0
 */
public enum class WorldWeather {
    /**
     * Clear weather without rain or thunderstorms.
     * @since 1.0.0
     */
    CLEAR,

    /**
     * There's snow, rain, or thunderstorms.
     * @since 1.0.0
     */
    DOWNFALL,
}
